// Fresh, synthetic localhost databases only. Never use a hosted Supabase connection.
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const read = (p) => fs.readFile(path.join(root, p), 'utf8');
const migration = 'supabase/migrations/20261104041151_phone_number_purchase_operations.sql';
let db, pg;

try {
  if (process.env.PGURL) {
    const url = new URL(process.env.PGURL);
    assert(['postgres:', 'postgresql:'].includes(url.protocol), 'PostgreSQL URL required');
    assert(['127.0.0.1', 'localhost'].includes(url.hostname), 'Only disposable localhost PostgreSQL');
    assert(/^\/phone_number_purchases_[a-z0-9_]+$/.test(url.pathname), 'Use a dedicated phone_number_purchases_* database');
    assert(!url.search && !url.hash, 'Connection override parameters are forbidden');
    assert(!url.href.includes('jncvvsvckxhqgqvkppmj'), 'Production project reference forbidden');
    const safeUrl = new URL(url); safeUrl.password = '';
    console.log(`LOCAL ONLY: ${safeUrl.href}`);
    const { default: postgres } = await import('postgres');
    pg = postgres(url.href, { max: 6, onnotice: () => {}, connection: { application_name: 'phone_number_purchases_synthetic_tests' } });
    const session = await pg.reserve();
    db = {
      exec: (s) => session.unsafe(s),
      query: async (s, p = []) => ({ rows: await session.unsafe(s, p) }),
      close: async () => { session.release(); await pg.end(); },
    };
    const [server] = (await db.query('select host(inet_server_addr()) as host, current_database() as name')).rows;
    assert(['127.0.0.1', '::1'].includes(server.host), 'The actual server must be loopback');
    assert.equal(`/${server.name}`, url.pathname);
  } else {
    const { PGlite } = await import(process.env.PGLITE_MODULE || '@electric-sql/pglite');
    db = new PGlite();
    console.log('LOCAL ONLY: new in-memory PGlite instance (synthetic data)');
  }

  const q = async (sql, params) => (await db.query(sql, params)).rows;
  const source = async (p) => db.exec(await read(p));
  const [existing] = await q("select count(*)::int as n from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname in ('public','private','auth') and c.relkind in ('r','p','v','m','f')");
  assert.equal(existing.n, 0, 'Refuse any non-empty database; create a fresh synthetic database for each run');
  console.log('Verified empty database; every row below is generated by synthetic fixtures.');

  // Reuse the existing Inbounds fixture and immutable migrations, including real number guards.
  await source('supabase/tests/inbound_harness.sql');
  for (const name of ['20260823222528_inbound_identity_foundation', '20260823222805_inbound_claim_lifecycle', '20260823222926_recording_source_sid']) {
    await source(`supabase/migrations/${name}.sql`);
  }
  await source('supabase/tests/inbound_v2_harness.sql');
  for (const name of ['20260914000530_inbound_agent_settings_and_registrations', '20260915025931_inbound_routing_v2_settings', '20260915035141_inbound_route_attempts_d13_and_recovery', '20260915053646_inbound_voicemails']) {
    await source(`supabase/migrations/${name}.sql`);
  }
  await source('supabase/tests/inbounds/extension.sql');
  for (const f of JSON.parse(await read('supabase/tests/inbounds/live-routing-preimage.json'))) await db.exec(f.definition);
  await db.exec(JSON.parse(await read('supabase/tests/inbounds/live-claim-preimage.json')).definition);
  await source('supabase/migrations/20261103191631_inbounds_room_v1.sql');

  // Test-only additions reproduce the inspected live purchase columns and global phone uniqueness.
  await db.exec(`
    ALTER TABLE public.organizations ADD twilio_subaccount_sid text;
    ALTER TABLE public.phone_numbers ADD twilio_sid text, ADD friendly_name text,
      ADD area_code text, ADD trust_hub_status text, ADD created_at timestamptz DEFAULT now(),
      ADD updated_at timestamptz DEFAULT now(), ADD UNIQUE(phone_number);
    -- Deliberately permissive defaults ensure the new migration really removes inherited grants.
    ALTER DEFAULT PRIVILEGES IN SCHEMA private GRANT ALL ON TABLES TO anon, authenticated, service_role;
    ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT EXECUTE ON FUNCTIONS TO anon, authenticated, service_role;
    ALTER DEFAULT PRIVILEGES IN SCHEMA private GRANT EXECUTE ON FUNCTIONS TO anon, authenticated, service_role;
  `);
  const functions = "select p.oid::text as id, pg_get_functiondef(p.oid) as definition, p.proacl::text as acl from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname in ('public','private') and p.prokind='f' order by p.oid";
  const beforeFunctions = await q(functions);
  const tables = "select c.oid::text as id, c.relrowsecurity, c.relacl::text as acl from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname in ('public','private') and c.relkind='r' order by c.oid";
  const beforeTables = await q(tables);
  await source(migration);
  const afterFunctions = new Map((await q(functions)).map((r) => [r.id, r]));
  const afterTables = new Map((await q(tables)).map((r) => [r.id, r]));
  for (const row of beforeFunctions) assert.deepEqual(afterFunctions.get(row.id), row, 'Existing function body/ACL must remain unchanged');
  for (const row of beforeTables) assert.deepEqual(afterTables.get(row.id), row, 'Existing table RLS/ACL must remain unchanged');

  await source('supabase/tests/phone_number_purchases.sql');
  const [{ n: assertionCount }] = await q('select count(*)::int as n from public.phone_purchase_test_results');
  console.log(`PASS: ${assertionCount} SQL assertions`);
  console.log('PASS: purchase SQL authorization, quote binding, replay, ownership, receipts, atomic recovery, ACL/RLS/search_path and real Inbounds/outbound guards');
  if (pg) {
    await import('./concurrency.mjs').then((m) => m.run(pg));
    console.log('PASS: native PostgreSQL simultaneous claims, cross-organization attempts, request collisions, receipt uniqueness and finalization');
  } else {
    console.log('LIMIT: PGlite has one session; PGURL is required for actual contention evidence.');
  }
} catch (error) {
  console.error(error.message, error.detail || '', error.where || '');
  process.exitCode = 1;
} finally {
  await db?.close();
}
