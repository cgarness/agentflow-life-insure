#!/usr/bin/env node
// Generates src/components/reports/regional/usStatePaths.ts from `npm pack us-atlas@3.0.1` (D5 §5). Node built-ins only.
// Run by hand in an empty temp directory outside the repository; the tarball is read as data, never executed.
//   node scripts/geo/build-us-state-paths.mjs <us-atlas-3.0.1.tgz> <output .ts>
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { gunzipSync } from "node:zlib";

const PINS = {
  tarball: "e6daba1800885868303ad3549da62f85a557b8142bb72629ec15651de62f9c5d",
  input: "6e7bb086a3c791490361968a3094f377f7726c5d0c4900fec03cc42db2305a3d",
  license: "8048290dfdb6e83fbed17e8985c8cfc4ce9da9b842642f3d3e497280790cfa31",
};
const FIPS = { "01": "AL", "02": "AK", "04": "AZ", "05": "AR", "06": "CA", "08": "CO", "09": "CT", "10": "DE", "11": "DC", "12": "FL",
  "13": "GA", "15": "HI", "16": "ID", "17": "IL", "18": "IN", "19": "IA", "20": "KS", "21": "KY", "22": "LA", "23": "ME", "24": "MD",
  "25": "MA", "26": "MI", "27": "MN", "28": "MS", "29": "MO", "30": "MT", "31": "NE", "32": "NV", "33": "NH", "34": "NJ", "35": "NM",
  "36": "NY", "37": "NC", "38": "ND", "39": "OH", "40": "OK", "41": "OR", "42": "PA", "44": "RI", "45": "SC", "46": "SD", "47": "TN",
  "48": "TX", "49": "UT", "50": "VT", "51": "VA", "53": "WA", "54": "WV", "55": "WI", "56": "WY" };
const sha = (b) => createHash("sha256").update(b).digest("hex");
const refuse = (m) => { console.error("REFUSING: " + m); process.exit(2); };

const [tgzPath, outPath] = process.argv.slice(2);
if (!tgzPath || !outPath) refuse("usage: build-us-state-paths.mjs <us-atlas-3.0.1.tgz> <output .ts>");
const tgz = readFileSync(tgzPath);
if (sha(tgz) !== PINS.tarball) refuse("tarball sha256 mismatch");
// ustar: 512-byte headers; name at 0..100, size (octal) at 124..136.
const tar = gunzipSync(tgz), files = {};
for (let o = 0; o + 512 <= tar.length;) {
  const name = tar.subarray(o, o + 100).toString("utf8").replace(/\0.*$/s, "");
  if (!name) break;
  const size = parseInt(tar.subarray(o + 124, o + 136).toString("utf8").replace(/\0.*$/s, "").trim() || "0", 8);
  files[name] = tar.subarray(o + 512, o + 512 + size);
  o += 512 + Math.ceil(size / 512) * 512;
}
const input = files["package/states-albers-10m.json"], license = files["package/LICENSE"];
if (!input || sha(input) !== PINS.input) refuse("states-albers-10m.json sha256 mismatch");
if (!license || sha(license) !== PINS.license) refuse("LICENSE sha256 mismatch");

const topo = JSON.parse(input.toString("utf8"));
const t = topo.transform;
const arcs = topo.arcs.map((arc) => {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => (t ? [(x += dx) * t.scale[0] + t.translate[0], (y += dy) * t.scale[1] + t.translate[1]] : [dx, dy]));
});
const ring = (indexes) => indexes.flatMap((i, n) => {
  const pts = i < 0 ? [...arcs[~i]].reverse() : arcs[i];
  return n === 0 ? pts : pts.slice(1);
});
// Integer coordinates; one absolute move per ring, then relative line-tos with the command letter written once
// (SVG repeats it implicitly) and no separator before a negative number. Coordinates are unchanged by the encoding.
const num = (prev, n) => (n < 0 || prev === "" ? `${n}` : ` ${n}`);
function pathFor(rings) {
  let d = "";
  for (const r of rings) {
    let px = null, py = null, seg = "";
    for (const [fx, fy] of r) {
      const x = Math.round(fx), y = Math.round(fy);
      if (px === null) d += `M${x}${num("x", y)}`;
      else if (x !== px || y !== py) { seg += num(seg, x - px) + num("x", y - py); }
      px = x; py = y;
    }
    d += (seg ? "l" + seg : "") + "z";
  }
  return d;
}
const geoms = topo.objects.states.geometries;
if (geoms.length !== 51) refuse(`expected 51 geometries, found ${geoms.length}`);
const paths = {};
for (const g of geoms) {
  const abbr = FIPS[String(g.id).padStart(2, "0")];
  if (!abbr) refuse(`unknown FIPS code ${g.id}`);
  const polys = g.type === "Polygon" ? [g.arcs] : g.arcs;
  paths[abbr] = pathFor(polys.flatMap((p) => p.map(ring)));
}
const sorted = Object.fromEntries(Object.keys(paths).sort().map((k) => [k, paths[k]]));
const licenseText = license.toString("utf8").trim();
const source = "Derived from the U.S. Census Bureau's cartographic state boundaries, 2017 edition (https://www2.census.gov/geo/tiger/GENZ2017/shp/), via us-atlas 3.0.1 states-albers-10m.json, projected with d3.geoAlbersUsa.";
const notice = "us-atlas 3.0.1 (ISC licence). " + source;
const out = `/*! US state boundaries for the Reports Regional map. Generated by scripts/geo/build-us-state-paths.mjs; do not edit.
${licenseText.split("\n").map((l) => " * " + l).join("\n").replace(/ +$/gm, "")}
 *
 * ${source}
 */
export const US_STATE_GEOMETRY = {
  notice: ${JSON.stringify(notice)},
  license: ${JSON.stringify(licenseText)},
  source: ${JSON.stringify(source)},
  viewBox: "-58 12 1016 596",
  paths: ${JSON.stringify(sorted)} as Record<string, string>,
} as const;
`;
writeFileSync(outPath, out);
console.log(`wrote ${outPath}: ${Object.keys(sorted).length} states, ${Buffer.byteLength(out)} B, sha256 ${sha(Buffer.from(out))}`);
