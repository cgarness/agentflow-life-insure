#!/usr/bin/env python3
"""Frozen reference for the Reports v3 differential harness (Batch 7, Phase E).

Builds the reference schema from the reviewed baseline pinned in
supabase/tests/reference/reports_v3_reference_manifest.json:

- every function that the pinned source files define, copied byte for byte from the baseline commit;
- mechanically renamed into the reference schema (each defined schema.name( is redirected there, so
  calls between baseline functions stay inside the reference);
- plus exactly one documented, reference-only repair: the UUID cast guard fixed in Batch 6 (without it
  the baseline raises 22P02 at scale), applied once and only once.

Every source blob, every source hash and the generated SQL hash are checked against the manifest; any
drift refuses. The case inventory (expected outcome type of every differential case) is emitted as the
table rt.dx_expected, so expected results come from the reviewed baseline, never from the code under test.

Usage:
  python3 scripts/reports_v3_reference.py [--manifest PATH] [--out PATH]
  python3 scripts/reports_v3_reference.py --print-hashes   (maintenance only: show the computed hashes)
"""
import argparse
import hashlib
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_MANIFEST = os.path.join(ROOT, 'supabase', 'tests', 'reference', 'reports_v3_reference_manifest.json')
FUNCTION = re.compile(r'^CREATE FUNCTION .*?^(?:\$\$|END \$\$);\s*$', re.S | re.M)
DEFINED = re.compile(r'CREATE FUNCTION (private|public)\.([a-z0-9_]+)\(')


def git(*args: str) -> bytes:
    return subprocess.run(['git', *args], cwd=ROOT, check=True, capture_output=True).stdout


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def build(manifest: dict) -> tuple[str, list[dict]]:
    commit = manifest['baseline_commit']
    schema = manifest['reference_schema']
    if not re.fullmatch(r'[0-9a-f]{40}', commit) or not re.fullmatch(r'[a-z][a-z0-9_]*', schema):
        sys.exit('REFUSING: the manifest commit or reference schema is malformed.')
    found = []
    blocks = []
    for src in manifest['sources']:
        blob = git('rev-parse', f"{commit}:{src['path']}").decode().strip()
        data = git('cat-file', 'blob', blob)
        found.append({'path': src['path'], 'git_blob': blob, 'sha256': sha256(data)})
        blocks.extend(m.group(0) for m in FUNCTION.finditer(data.decode('utf-8')))
    names = set()
    for b in blocks:
        m = DEFINED.match(b)
        if not m:
            sys.exit('REFUSING: unexpected function header: ' + b[:80])
        names.add((m.group(1), m.group(2)))
    renamed = []
    for b in blocks:
        for sch, name in names:
            b = re.sub(rf'\b{sch}\.{name}\(', f'{schema}.{name}(', b)
        renamed.append(b)
    body = '\n\n'.join(renamed)
    patch = manifest['reference_only_repair']
    if body.count(patch['from']) != 1:
        sys.exit('REFUSING: the reference-only repair target must occur exactly once (found %d).' % body.count(patch['from']))
    body = body.replace(patch['from'], patch['to'])
    header = (f"-- Generated by scripts/reports_v3_reference.py from {commit}: {len(blocks)} functions renamed into "
              f"{schema}, plus the reference-only repair ({patch['id']}). Do not edit.\n")
    sql = (header + f'DROP SCHEMA IF EXISTS {schema} CASCADE;\nCREATE SCHEMA {schema};\nSET check_function_bodies = off;\n'
           + body + '\nRESET check_function_bodies;\n'
           # Harness hygiene, outside the copied bodies: no reference function is client-executable. USAGE lets the
           # harness call the reference readers through the same authenticated path as the public readers, only while it
           # grants EXECUTE inside a comparison transaction (rt.dx_grants).
           + f'REVOKE ALL ON SCHEMA {schema} FROM PUBLIC;\n'
           + f'GRANT USAGE ON SCHEMA {schema} TO authenticated;\n'
           + f'REVOKE ALL ON ALL FUNCTIONS IN SCHEMA {schema} FROM PUBLIC, anon, authenticated, service_role;\n')
    return sql, found


def inventory_sql(manifest: dict) -> str:
    """rt.dx_expected: one row per reader-matrix case with its pinned expected outcome type."""
    inv = manifest['case_inventory']
    rows = []
    for p in inv['personas']:
        for reader in inv['readers'] + ['scope']:
            windows = [[None, None]] if reader == 'scope' else inv['windows']
            for s, e in windows:
                expected = p['scope_reader'] if reader == 'scope' else p['windowed']
                rows.append((p['who'], p['org'], p['scope'], p['agent'], reader, s, e, expected))
    def lit(v):
        return 'NULL' if v is None else "'" + str(v).replace("'", "''") + "'"
    values = ',\n  '.join('(' + ', '.join(lit(v) for v in r) + ')' for r in rows)
    totals = inv['expected_totals']
    retained = inv['retained_totals']
    scale = [(c['reader'], c['persona'], c['days'], c['filter_agent'], c['scope'], c['expected']) for c in inv['scale_cases']]
    scale_values = ',\n  '.join('(' + ', '.join(lit(v) for v in r) + ')' for r in scale)
    if len(rows) != int(totals['cases']):
        sys.exit('REFUSING: the inventory expands to %d cases, not the pinned %s.' % (len(rows), totals['cases']))
    return ('CREATE TABLE rt.dx_expected (who text, org text, scope text, agent text, reader text, start_date date, '
            'end_date date, expected text);\n'
            + (f'INSERT INTO rt.dx_expected VALUES\n  {values};\n' if rows else '')
            + "CREATE TABLE rt.dx_expected_totals AS SELECT "
            f"{int(totals['cases'])}::bigint AS cases, {int(totals['payload'])}::bigint AS payload, "
            f"{int(totals['refusal'])}::bigint AS refusal;\n"
            "CREATE TABLE rt.dx_retained_totals AS SELECT "
            f"{int(retained['state_resolver'])}::bigint AS state_resolver, {int(retained['journey'])}::bigint AS journey, "
            f"{int(retained['journey_by_agent'])}::bigint AS journey_by_agent;\n"
            'CREATE TABLE rt.dx_scale_expected (reader text, persona integer, days integer, filter_agent integer, scope text, '
            'expected text);\n'
            + (f'INSERT INTO rt.dx_scale_expected VALUES\n  {scale_values};\n' if scale else '')
            + f"CREATE TABLE rt.dx_manifest AS SELECT {lit(manifest['baseline_commit'])}::text AS baseline_commit, "
            f"{lit(json.dumps(manifest.get('approved_differences', [])))}::jsonb AS approved_differences;\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--manifest', default=DEFAULT_MANIFEST)
    ap.add_argument('--out')
    ap.add_argument('--print-hashes', action='store_true')
    args = ap.parse_args()
    with open(args.manifest, encoding='utf-8') as fh:
        manifest = json.load(fh)
    sql, found = build(manifest)
    if args.print_hashes:
        print(json.dumps({'sources': found, 'generated_sha256': sha256(sql.encode())}, indent=2))
        return
    for want, got in zip(manifest['sources'], found):
        if want != got:
            sys.exit(f"REFUSING: source drift for {want['path']}: manifest {want} != repository {got}")
    if len(found) != len(manifest['sources']):
        sys.exit('REFUSING: the manifest source list changed.')
    if sha256(sql.encode()) != manifest['generated_sha256']:
        sys.exit('REFUSING: the generated reference does not match the pinned hash.')
    out = sql + inventory_sql(manifest)
    if args.out:
        with open(args.out, 'w', encoding='utf-8') as fh:
            fh.write(out)
    else:
        sys.stdout.write(out)


if __name__ == '__main__':
    main()
