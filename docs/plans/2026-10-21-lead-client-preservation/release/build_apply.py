#!/usr/bin/env python3
"""Build the Gate 2 version-preserving apply statement for the Lead -> Client conversion preservation migration.

    python3 docs/plans/2026-10-21-lead-client-preservation/release/build_apply.py > apply_20261021200000.sql

The output is ONE ASCII-only SQL string, to be sent as a single request (one implicit transaction; any error rolls
everything back), with the same method as the Commissions center and insights Gate 2 releases:

* the migration's own `SET LOCAL lock_timeout '1s'` / `statement_timeout '60s'` bind the whole request;
* a DO block holds the reviewed file text as a dollar-quoted literal, its non-ASCII characters (box-drawing rules,
  arrows, dashes) as placeholders expanded server-side;
* it refuses unless the expanded text's MD5, SHA-256 and UTF-8 length equal the reviewed values, the hosted head
  observed at the Gate 2 preflight is recorded, nothing is recorded at or after this version (hosted history, not
  source filenames), and the caller is postgres;
* it EXECUTEs the text unchanged (the file's own preimage, replay, metadata and post-image guards run inside),
  re-checks the role, and records (version, name, ARRAY[text]) in supabase_migrations.schema_migrations.

This script only writes the statement; it never connects to a database. Running the output in production requires
Chris's Gate 2 approval naming this file, version and checksum.
"""
import hashlib
import sys
from pathlib import Path

VERSION = "20261021200000"
NAME = "lead_client_conversion_preservation"
SHA256 = "ce189016d2ca39af780c9f61909f74dd65c13b867a6238d8498cb9ce23729ae5"
MD5 = "3b8f527b3991660d2ae0d03fe42b1af7"
LENGTH = 24911
# The hosted head observed by the Gate 2 preflight (2026-10-21 17:42 UTC).
PREREQUISITES = ("20261021180000",)
OUTER, INNER = "$agentflow_lead_conversion_release$", "$agentflow_lead_conversion_migration$"

root = Path(__file__).resolve().parents[4]
raw = (root / "supabase" / "migrations" / f"{VERSION}_{NAME}.sql").read_bytes()
if (hashlib.sha256(raw).hexdigest(), hashlib.md5(raw).hexdigest(), len(raw)) != (SHA256, MD5, LENGTH):
    sys.exit("REFUSING: the migration file differs from the reviewed bytes")
text = raw.decode("utf-8")
for marker in (OUTER, INNER, "@@U"):
    if marker in text:
        sys.exit(f"REFUSING: {marker} occurs in the migration text")

codepoints = sorted({ord(c) for c in text if ord(c) > 127})
literal = text
for cp in codepoints:
    literal = literal.replace(chr(cp), f"@@U{cp:04X}@@")
expand = "\n".join(f"  v_sql := replace(v_sql, '@@U{cp:04X}@@', chr({cp}));" for cp in codepoints)
prereq = ", ".join(f"'{v}'" for v in PREREQUISITES)

statement = f"""-- Lead -> Client conversion preservation Gate 2 apply: {VERSION} / {NAME}. Generated by build_apply.py from
-- the reviewed file (SHA-256 {SHA256}); do not edit. Send as ONE request.
SET LOCAL lock_timeout = '1s';
SET LOCAL statement_timeout = '60s';
DO {OUTER}
DECLARE
  v_sql text := {INNER}{literal}{INNER};
BEGIN
{expand}
  IF md5(v_sql) <> '{MD5}'
     OR encode(sha256(convert_to(v_sql, 'UTF8')), 'hex') <> '{SHA256}'
     OR octet_length(convert_to(v_sql, 'UTF8')) <> {LENGTH} THEN
    RAISE EXCEPTION 'release text differs from the reviewed migration; refusing';
  END IF;
  IF (SELECT count(*) FROM supabase_migrations.schema_migrations WHERE version IN ({prereq})) <> {len(PREREQUISITES)} THEN
    RAISE EXCEPTION 'the hosted head observed at preflight is not recorded; refusing';
  END IF;
  IF EXISTS (SELECT 1 FROM supabase_migrations.schema_migrations WHERE version >= '{VERSION}') THEN
    RAISE EXCEPTION 'version {VERSION} is recorded or would not sort last in the hosted history; refusing';
  END IF;
  IF current_user <> 'postgres' THEN
    RAISE EXCEPTION 'apply as postgres; refusing';
  END IF;
  EXECUTE v_sql;
  IF current_user <> 'postgres' THEN
    RAISE EXCEPTION 'the role changed during the migration; refusing';
  END IF;
  INSERT INTO supabase_migrations.schema_migrations(version, name, statements) VALUES ('{VERSION}', '{NAME}', ARRAY[v_sql]);
END
{OUTER};
"""
assert statement.isascii()
sys.stdout.write(statement)
